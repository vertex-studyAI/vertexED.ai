#!/usr/bin/env node

import { execFileSync } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

import { normalizeImmutableGitSha } from './immutable-revision.mjs';

const DEFAULT_OUTPUT = resolve('api/_generated/build-revision.js');

export function normalizeBuildRevision(value) {
  return normalizeImmutableGitSha(value);
}

function defaultRunGit(args) {
  return execFileSync('git', args, {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
}

function readDeclaredRevision(env, key) {
  const raw = env[key];
  if (raw == null || String(raw).trim() === '') return { present: false, revision: null };
  return { present: true, revision: normalizeBuildRevision(raw) };
}

export function resolveBuildRevision({ env = process.env, runGit = defaultRunGit } = {}) {
  const source = readDeclaredRevision(env, 'SOURCE_SHA');
  const vercel = readDeclaredRevision(env, 'VERCEL_GIT_COMMIT_SHA');

  if ((source.present && !source.revision) || (vercel.present && !vercel.revision)) {
    return null;
  }
  if (source.revision && vercel.revision && source.revision !== vercel.revision) {
    return null;
  }
  if (source.revision) return source.revision;
  if (vercel.revision) return vercel.revision;

  const githubRevision = normalizeBuildRevision(env.GITHUB_SHA);
  if (githubRevision) return githubRevision;

  try {
    return normalizeBuildRevision(runGit(['rev-parse', 'HEAD']));
  } catch {
    return null;
  }
}

export function requiresImmutableBuildRevision(env = process.env) {
  return env.VERTEXED_REQUIRE_BUILD_REVISION === '1' || env.VERCEL === '1';
}

export async function writeBuildRevisionModule({
  outputPath = DEFAULT_OUTPUT,
  env = process.env,
  runGit = defaultRunGit,
  required = requiresImmutableBuildRevision(env),
} = {}) {
  const revision = resolveBuildRevision({ env, runGit });

  if (!revision && required) {
    throw new Error(
      'Unable to resolve an immutable Git revision for this deploy-relevant build. ' +
      'Refusing to produce an unverifiable deployment artifact.',
    );
  }

  const contents = [
    '// Generated by scripts/generate-build-revision.mjs. Do not edit by hand.',
    `export const BUILD_REVISION = ${revision ? JSON.stringify(revision) : 'null'};`,
    '',
  ].join('\n');

  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, contents, 'utf8');
  return revision;
}

async function run() {
  const revision = await writeBuildRevisionModule();
  if (revision) {
    console.log(`[build-revision] stamped ${revision}`);
  } else {
    console.log('[build-revision] no immutable revision available; wrote null local-development stamp');
  }
}

const invokedPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : '';
if (import.meta.url === invokedPath) {
  run().catch((error) => {
    console.error(`[build-revision] ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  });
}
