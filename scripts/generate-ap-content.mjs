import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { isApCourse } from '../contracts/apContent.js';

const root = resolve(import.meta.dirname, '..');
const source = resolve(root, 'src/content/ap');
const output = resolve(root, 'public/ap-content');
const check = process.argv.includes('--check');
const courses = [];
for (const name of (await readdir(source)).filter((name) => name.endsWith('.json')).sort()) {
  const course = JSON.parse(await readFile(resolve(source, name), 'utf8'));
  if (!isApCourse(course) || name !== `${course.slug}.json`) throw new Error(`Invalid AP content: ${name}`);
  courses.push(course);
}
if (courses.length !== 42) throw new Error(`Expected the 42 current AP courses; found ${courses.length}.`);
if (new Set(courses.map((course) => course.title)).size !== 42) throw new Error('Duplicate AP course titles.');
const summaries = courses.map((course) => {
  const { modules, ...details } = course;
  return {
    ...details,
    contentSha256: createHash('sha256').update(`${JSON.stringify(course)}\n`).digest('hex'),
    modules: modules.map(({ id, title, frameworkUnit, focus }) => ({ id, title, frameworkUnit, focus })),
    questionCount: modules.reduce((sum, unit) => sum + unit.questions.length, 0),
  };
});
const catalogue = `// Generated by scripts/generate-ap-content.mjs from original course files.\nimport type { ApCourseSummary } from './apTypes';\nexport const AP_COURSES: ApCourseSummary[] = ${JSON.stringify(summaries, null, 2)};\nexport const AP_TOTALS = { courses: AP_COURSES.length, modules: AP_COURSES.reduce((sum, course) => sum + course.modules.length, 0), questions: AP_COURSES.reduce((sum, course) => sum + course.questionCount, 0) };\n`;
async function emit(path, contents) {
  if (check) {
    if (await readFile(path, 'utf8') !== contents) throw new Error(`Stale generated AP content: ${path}`);
  } else await writeFile(path, contents);
}
if (!check) await mkdir(output, { recursive: true });
for (const course of courses) await emit(resolve(output, `${course.slug}.json`), `${JSON.stringify(course)}\n`);
await emit(resolve(root, 'src/content/apCatalogue.ts'), catalogue);
console.log(`AP content ${check ? 'verified' : 'generated'}: ${courses.length} courses, ${summaries.reduce((n, c) => n + c.modules.length, 0)} modules, ${summaries.reduce((n, c) => n + c.questionCount, 0)} questions.`);
